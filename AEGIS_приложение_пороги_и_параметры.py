# ---------- 10. K-0.14 ----------
def k014_choose(opts):
    """opts: список (власть, цель1, цель2, ограничение); власть и ограничение — меньше лучше, цели — больше лучше."""
    pmin = min(o[0] for o in opts)
    s1 = [o for o in opts if o[0] == pmin]
    dom = lambda a, b: (a[1] >= b[1] and a[2] >= b[2]) and (a[1] > b[1] or a[2] > b[2])
    s2 = [o for o in s1 if not any(dom(x, o) for x in s1)]
    rmin = min(o[3] for o in s2)
    return [o for o in s2 if o[3] == rmin]

def k014_check(vals=(0, 1, 2), max_opts=3):
    import itertools as it
    pts = list(it.product(vals, repeat=4))
    count = 0
    for r in range(1, max_opts + 1):
        for opts in it.combinations(pts, r):
            ch = k014_choose(list(opts))
            count += 1
            if not ch:
                return False, count
            pmin = min(o[0] for o in opts)
            for c in ch:
                if c[0] != pmin:
                    return False, count
                if any(o[0] == pmin and o[1] >= c[1] and o[2] >= c[2] and (o[1] > c[1] or o[2] > c[2]) for o in opts):
                    return False, count
    return True, count

# ---------- 11. независимая проверка до выпуска (В-6) ----------
# Ошибки текста и моделей различаются заметностью: ошибку i каждый независимый проверяющий находит с
# вероятностью p_i. Утверждать, что ошибок нет, нельзя (K-10). Можно гарантировать другое: если последний
# круг из r новых проверяющих области не нашёл ни одной новой существенной ошибки, то каждая оставшаяся
# ошибка с заметностью не ниже p_min пережила бы такой круг с вероятностью не больше (1 - p_min)^r.
def reviewers_needed(p_min=1/3, alpha=0.05):
    return math.ceil(math.log(alpha) / math.log(1 - p_min))

def survival(p, r):
    return (1 - p) ** r

def chapman_remaining(n1, n2, m):
    """Оценка числа ненайденных ошибок по двум проверяющим (повторный отлов, оценка Чепмена)."""
    return (n1 + 1) * (n2 + 1) / (m + 1) - 1 - (n1 + n2 - m)

def sim_rounds(D=20, a=1.0, b=2.0, r=8, max_rounds=30, trials=2000, seed=7):
    """Круги: в каждом r новых проверяющих; найденное исправляется; конец — круг без новых находок.
    Возвращает долю случаев, где осталась ошибка с заметностью >= 1/3, и среднее число оставшихся."""
    rnd = random_module.Random(seed)
    left_easy = left_all = 0
    rounds_total = 0
    for _ in range(trials):
        p = [rnd.betavariate(a, b) for _ in range(D)]
        alive = set(range(D))
        for rd in range(max_rounds):
            found = {i for i in alive if any(rnd.random() < p[i] for _ in range(r))}
            rounds_total += 1
            if not found:
                break
            alive -= found
        left_all += len(alive)
        left_easy += any(p[i] >= 1 / 3 for i in alive)
    return left_easy / trials, left_all / trials, rounds_total / trials

