import math

def lcomb(a, b):
    return math.lgamma(a + 1) - math.lgamma(b + 1) - math.lgamma(a - b + 1) if 0 <= b <= a else -math.inf

def betabin(x, n, mean, rho):
    """Бета-биномиальное распределение: x «событий» из n при среднем mean и внутриклассовой корреляции rho."""
    if n == 0:
        return 1.0 if x == 0 else 0.0
    if rho <= 0:
        return math.exp(lcomb(n, x) + (x * math.log(mean) if x else 0) + ((n - x) * math.log(1 - mean) if n - x else 0))
    a = mean * (1 - rho) / rho; b = (1 - mean) * (1 - rho) / rho
    lb = lambda u, v: math.lgamma(u) + math.lgamma(v) - math.lgamma(u + v)
    return math.exp(lcomb(n, x) + lb(x + a, n - x + b) - lb(a, b))

# ---------------------------------------------------------------------------
# 1. РЕШЕНИЯ РАВНЫХ (раздел Р)
# V голосующих; доля b — согласованный блок, всегда голосует во вред.
# Добросовестные приходят с вероятностью t и голосуют верно с вероятностью ~p (корреляция rho).
# Правило Р-3: принять, если «за» > tau от проголосовавших И «за» >= phi от всех V.
# ---------------------------------------------------------------------------
def decision_errors(V, b, t, p, rho, tau=0.5, phi=0.20):
    B = round(b * V); H = V - B; harmful = blocked = 0.0
    for h in range(H + 1):
        ph = math.exp(lcomb(H, h) + (h * math.log(t) if h else 0) + ((H - h) * math.log(1 - t) if H - h else 0))
        if ph < 1e-15:
            continue
        n = B + h
        for x in range(h + 1):          # вредное: блок «за», добросовестные «за» по ошибке
            yes = B + x
            if yes > tau * n and yes >= phi * V:
                harmful += ph * betabin(x, h, 1 - p, rho)
        for x in range(h + 1):          # полезное: блок «против», добросовестные «за» верно
            yes = x
            if not (yes > tau * n and yes >= phi * V):
                blocked += ph * betabin(x, h, p, rho)
    return harmful, blocked

def theorem_window(b, p):
    """Теорема (V->inf, rho=0, полная явка): допустимые tau лежат в (b+(1-b)(1-p), (1-b)p);
    окно не пусто тогда и только тогда, когда b < (2p-1)/(2p)."""
    return b + (1 - b) * (1 - p), (1 - b) * p, (2 * p - 1) / (2 * p)


def sybil_effective_block(b, s):
    """Поддельные псевдонимы (атака Сивиллы). b — доля согласованного блока среди реальных людей;
    s — доля поддельных псевдонимов среди всех имеющих право голоса (все они голосуют с блоком).
    Эффективная доля блока b' = b(1-s) + s. Решения устойчивы (теорема), пока b' < (2p-1)/(2p)."""
    return b * (1 - s) + s

def sybil_max_share(b, p):
    """Наибольшая доля поддельных псевдонимов, при которой окно порога ещё не пусто."""
    lim = (2 * p - 1) / (2 * p)
    return max(0.0, (lim - b) / (1 - b))

def decision_errors_sybil(V, b, s, t, p, rho, tau=0.5, phi=0.20):
    """V — число реальных людей; поддельные S = s/(1-s)*V добавляются к блоку и к знаменателю phi."""
    S = round(s / (1 - s) * V)
    return decision_errors(V + S, (round(b * V) + S) / (V + S), t, p, rho, tau, phi)


# ---------------------------------------------------------------------------
# 1б. ДОПУСК К ГОЛОСУ (Р-6, Р-7): окно W месяцев, не менее m месяцев с вкладом, k поручителей по жребию
# Честные: месячная активность a ~ Beta(A,B). Противник: бюджет beta*V принятых вкладов в месяц;
# поддельный вклад разоблачается при приёмке с вер. delta. Поручитель по жребию — поддельный с вер. s,
# честный обманут с вер. f. Доля подделок s* — неподвижная точка.
# Вывод модели: ограничение активности не опускает долю подделок ниже ~beta/q; решает поручительство по жребию.
# ---------------------------------------------------------------------------
def _beta_w(a, A, B):
    return math.exp((A - 1) * math.log(a) + (B - 1) * math.log(1 - a)
                    - (math.lgamma(A) + math.lgamma(B) - math.lgamma(A + B)))

def _below(W, m, a):
    return sum(math.comb(W, j) * a ** j * (1 - a) ** (W - j) for j in range(m))

def honest_exclusion(W, m, A=2.0, B=3.0, a0=0.25, grid=400):
    """Доля постоянных честных (активность a >= a0), не получающих голос."""
    pts = [a0 + (1 - a0) * (i + 0.5) / grid for i in range(grid)]
    w = [_beta_w(a, A, B) for a in pts]
    return sum(wi * _below(W, m, a) for wi, a in zip(w, pts)) / sum(w)

def honest_voting_share(W, m, A=2.0, B=3.0, grid=400):
    return sum(_beta_w((i + .5) / grid, A, B) * (1 - _below(W, m, (i + .5) / grid)) for i in range(grid)) / grid

def sybil_fixed_point(W, m, k, beta, delta, f, q):
    cand = beta * W / m * (1 - delta) ** m
    s = 0.0
    for _ in range(1000):
        S = cand * (s + (1 - s) * f) ** k
        s_new = S / (q + S)
        if abs(s_new - s) < 1e-12:
            break
        s = s_new
    return s

def admission_levels(target=0.05):
    """Для каждого сценария (beta, f) — правило с наименьшим исключением честных при s* <= target."""
    cfg = [(W, m, honest_voting_share(W, m), honest_exclusion(W, m)) for W in (6, 12, 24) for m in range(1, W + 1)]
    out = []
    for beta in (0.02, 0.05, 0.10):
        for f in (0.3, 0.6, 0.9):
            best = None
            for W, m, q, e in cfg:
                for k in range(1, 6):
                    sv = sybil_fixed_point(W, m, k, beta, 0.05, f, q)
                    if sv <= target and (best is None or (e, k, W) < best[0]):
                        best = ((e, k, W), W, m, k, sv)
            out.append((beta, f, best))
    return out

# ---------------------------------------------------------------------------
# 2. ПОДПИСЬ ВЫПУСКОВ t ИЗ n (раздел В-1)
# За период ротации ключ теряется с вероятностью l, компрометируется с вероятностью c; общая причина rho.
# ---------------------------------------------------------------------------
def signing_risk(n, t, l, c, rho):
    unavailable = sum(betabin(x, n, l, rho) for x in range(n - t + 1, n + 1))
    forged = sum(betabin(x, n, c, rho) for x in range(t, n + 1))
    return unavailable, forged

def best_signing(l, c, rho, forge_max=1e-4, nmax=9):
    """Подделка — катастрофа: сначала подделка <= forge_max, затем минимум недоступности. t>=2 (K-8)."""
    out = []
    for n in range(2, nmax + 1):
        ok = [(signing_risk(n, t, l, c, rho), t) for t in range(2, n + 1)]
        ok = [x for x in ok if x[0][1] <= forge_max]
        if ok:
            (u, f), t = min(ok)
            out.append((n, t, f, u))
    return out


SIGN_GRID = [(l, c, r) for l in (.03, .05, .1) for c in (.005, .01, .02, .03) for r in (.01, .02, .05, .1)]
SIGN_LAMS = (0.02, 0.05, 0.1, 0.2, 0.5)

def signing_robust_choice(nmax=31):
    """Устойчивый выбор схемы подписи (В-1). Потеря в сценарии s = подделка/1e-4 + недоступность/1e-3
    (нормировано на цели) + lam*n (вес числа людей; lam неизвестен и тоже перебирается).
    Выбирается (n, t), t > n/2, минимизирующая наибольшее по сценариям и lam отношение к оптимуму сценария.
    Без веса числа людей больше держателей всегда лучше, но с убывающей отдачей: общая причина задаёт предел."""
    cands = [(n, t) for n in range(3, nmax + 1) for t in range(n // 2 + 1, n + 1)]
    L = {}
    for n, t in cands:
        for sc in SIGN_GRID:
            u, f = signing_risk(n, t, *sc); L[(n, t, sc)] = f / 1e-4 + u / 1e-3
    opt = {(sc, lam): min(L[(n, t, sc)] + lam * n for n, t in cands) for sc in SIGN_GRID for lam in SIGN_LAMS}
    ranked = sorted((max((L[(n, t, sc)] + lam * n) / opt[(sc, lam)] for sc in SIGN_GRID for lam in SIGN_LAMS), n, t) for n, t in cands)
    return ranked

