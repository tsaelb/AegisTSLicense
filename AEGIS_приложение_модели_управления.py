# 6. ПАТЕНТНОЕ СДЕРЖИВАНИЕ (Л-9)
# Иск длится до урегулирования tau ~ Exp(mu) месяцев; пока лицензия приостановлена, заявитель теряет v в месяц.
# Автоматическое прекращение: ожидаемая потеря v*mu. Через процедуру: мера вступает после срока D
# и только при доказанном нарушении (вер. P): P*v*E[(tau-D)+] = P*v*mu*exp(-D/mu).
# Относительная сила сдерживания = P*exp(-D/mu). Сдерживание есть, если ожидаемая потеря >= выгоды иска.
# ---------------------------------------------------------------------------
def patent_deterrence(P, D, mu):
    return P * math.exp(-D / mu)

