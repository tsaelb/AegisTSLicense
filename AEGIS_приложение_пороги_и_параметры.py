# ---------- биномиальные границы без внешних библиотек ----------
def binom_pmf(x, n, p):
    if p <= 0:
        return 1.0 if x == 0 else 0.0
    if p >= 1:
        return 1.0 if x == n else 0.0
    return math.exp(A.lcomb(n, x) + x * math.log(p) + (n - x) * math.log(1 - p))

def binom_cdf(x, n, p):
    return sum(binom_pmf(i, n, p) for i in range(0, x + 1))

def upper_bound(x, n, alpha=0.05):
    """Точная (Клоппер — Пирсон) односторонняя верхняя граница доли при x находках из n."""
    if x >= n:
        return 1.0
    lo, hi = 0.0, 1.0
    for _ in range(80):
        mid = (lo + hi) / 2
        if binom_cdf(x, n, mid) > alpha:
            lo = mid
        else:
            hi = mid
    return hi

def min_sample(bound, alpha=0.05):
    """Наименьший объём, при котором 0 находок даёт верхнюю границу не выше bound."""
    return math.ceil(math.log(alpha) / math.log(1 - bound))

def p_step_down(n, true_share, bound=0.025):
    """Вероятность за год, что граница по выборке n не превысит bound."""
    return sum(binom_pmf(x, n, true_share) for x in range(n + 1) if upper_bound(x, n) <= bound)

