def reserve_months(p_shock, mu, eps=0.01):
    """Запас R (мес.), при котором риск за год p_shock * P(восстановление дольше R) <= eps;
    срок восстановления — экспоненциальный со средним mu."""
    if p_shock <= eps:
        return 0
    return math.ceil(mu * math.log(p_shock / eps))

