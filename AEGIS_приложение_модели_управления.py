# 5. ТЕХНИЧЕСКИЕ ХРАНИТЕЛИ КАНАЛОВ (В-3, В-8)
# C каналов; у каждого команда из n хранителей с доступом «t из n»; команды не пересекаются,
# выбираются жребием без возвращения из N допущенных, среди которых M = ceil(b*N) недобросовестных.
# Канал выходит из строя, если: (1) инфраструктура канала недоступна (вер. f, общая причина rho_c между каналами);
# (2) захвачен: недобросовестных в команде >= t; (3) заблокирован: доступных добросовестных < t
#    (добросовестный недоступен за год с вер. l, общая причина rho внутри команды).
# Отказ распространения — все C каналов вышли из строя одновременно (подлинность выпусков защищает подпись В-1).
# ---------------------------------------------------------------------------


def hyper(a, N, M, n):
    if a < 0 or a > n or a > M or n - a > N - M: return 0.0
    return math.exp(lcomb(M, a) + lcomb(N - M, n - a) - lcomb(N, n))

def fail_given_a(a, n, t, l, rho):
    if a >= t: return 1.0                                   # захват
    h = n - a
    return sum(betabin(x, h, l, rho) for x in range(h + 1) if h - x < t)   # блокировка

def all_people_fail(k, N, M, n, t, l, rho):
    """Вероятность, что все k (из C) каналов выходят из строя по людям; команды тянутся последовательно."""
    memo = {}
    def rec(i, Nr, Mr):
        if i == k: return 1.0
        key = (i, Nr, Mr)
        if key in memo: return memo[key]
        s = 0.0
        for a in range(0, min(n, Mr) + 1):
            p = hyper(a, Nr, Mr, n)
            if p: s += p * fail_given_a(a, n, t, l, rho) * rec(i + 1, Nr - n, Mr - a)
        memo[key] = s; return s
    return rec(0, N, M)

def p_outage(N, b, C, n, t, l=0.05, rho=0.05, f=0.10, rho_c=0.1):
    if C * n > N: return None
    M = min(N, math.ceil(b * N))
    if f <= 0: return all_people_fail(C, N, M, n, t, l, rho)
    return sum(betabin(j, C, f, rho_c) * all_people_fail(C - j, N, M, n, t, l, rho) for j in range(C + 1))



