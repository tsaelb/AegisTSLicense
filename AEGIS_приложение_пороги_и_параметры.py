HASHES = [("64 бит (усечение)", 64), ("128 бит (усечение)", 128), ("SHA-256 / SHA3-256", 256), ("SHA-512 / SHA3-512", 512)]

# Порог обновления: запас (в битах) должен покрывать рост мощности за время обновления L при самом быстром
# темпе и одномоментную потерю J бит от криптоанализа. Исторически: MD5 — коллизия за ~2^18 вместо 2^64
# (потеря ~46 бит), SHA-1 — ~2^63 вместо 2^80 (потеря ~17 бит).
def renewal_margin(L=2.0, td_min=min(TDS), J=46, safety=2.0):
    return math.ceil(safety * L / td_min + J)

