# 3. КАНАЛЫ РАСПРОСТРАНЕНИЯ (раздел В-3)
# ---------------------------------------------------------------------------
def all_channels_fail(m, f, rho):
    return f ** m if rho <= 0 else betabin(m, m, f, rho)


# ---------------------------------------------------------------------------
# 4. КАЗНА (раздел 16, Д-4)
# Источники дают доход; каждый уходит за год с вероятностью l (общая причина rho).
# Худший случай концентрации: все источники на пределе доли s, их ceil(1/s).
# Риск — что ушедшие источники оставят доход ниже обязательных расходов (доля e от среднего дохода).
# Вывод модели: при сильной общей причине ухода никакой предел доли не помогает — защищают только
# малая доля обязательных расходов и запас.
# ---------------------------------------------------------------------------
def treasury_risk(s, e, l, rho):
    n = math.ceil(1 / s)
    return sum(betabin(x, n, l, rho) for x in range(n + 1) if x * s > 1 - e + 1e-12)

def treasury_cap(e, l, rho, eps=0.01):
    """Наибольший предел s, при котором риск <= eps для всех пределов не выше s (устойчиво к немонотонности)."""
    best = None
    for c in range(1, 101):
        sv = c / 100
        if sv > 1 - e or treasury_risk(sv, e, l, rho) > eps:
            break
        best = sv
    return best


